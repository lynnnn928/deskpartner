/**
 * 单调版本戳（1.0.73，`9947bf5a` 的配套修复）
 *
 * ## 它解决什么
 *
 * 乐观锁（`--if-updated-at`）靠"版本号变了没有"判断这条事项被动过。
 * 而原来版本号就是 `new Date().toISOString()` —— **毫秒精度**。
 * 实测（本机，20000 次连续取样）：**19974 次取到完全相同的值**。
 * 也就是说**同一毫秒内的两次写入，版本号一模一样**，
 * 乐观锁会静默判成"没人动过"，然后把别人刚改的内容原样盖掉。
 *
 * ⚠️ 这不是理论推演，是测试当场红的：`optimistic-lock.test.ts`
 * 那条"A 读过之后 B 改了，A 拿着旧版本改"直接失败 ——
 * 而失败方式是**放行**（本该拦住却报成功），正是本机制存在的理由被自己绕过。
 *
 * ## 做法：同毫秒内让时间"前进"1 毫秒
 *
 * 保证**同一进程内**单调递增，格式与原来完全一致（`...sssZ`）。
 *
 * 为什么不加"微秒序号"（如 `...587001`）：
 * - 那会造出**第三种格式**（库里已有 `...750Z` 与历史脚本留下的 `...587818`）；
 * - 格式一多，"字符串比较是否等于时间比较"就不再显然 ——
 *   而乐观锁的比对**完全建立在这个等式上**（见 `UpdateTodoInput.ifUpdatedAt`）。
 *
 * 代价（如实写在这里，不藏）：同一毫秒内的多次写入会得到
 * 相差 1~几毫秒的时间戳，**轻微偏离真实时刻**。
 * 判断"最近更新"这类用途完全无感（毫秒级），而它换来的是
 * **"不同写入 ⇒ 不同版本号"这个乐观锁赖以成立的直觉**。
 *
 * ## 已知边界（不假装全覆盖）
 *
 * 只保证**单进程内**单调。两个**进程**在同一毫秒各写一次时，
 * 各自从 0 开始，仍可能撞上。本机是四个写入方共写一份 SQLite，
 * 但跨进程写要过 IPC/CLI 序列化与 SQLite 写锁，落在同一毫秒的概率极低；
 * 且乐观锁本就是**检测手段而非强一致保证**。
 * 真要彻底闭合得让版本号由数据库生成（如 SQLite 的 rowid 或随机后缀）——
 * 那是更大的一次改动，此处不顺手做（**别把没验过的东西混进来**）。
 */
let lastMs = 0

/**
 * 取一个单调递增的 ISO 时间戳。
 *
 * 同一毫秒内连续调用会依次得到 `...:21.587Z`、`...:21.588Z`、`...:21.589Z`，
 * 而不是三个一模一样的值。
 */
export function nowVersion(): string {
  const ms = Date.now()
  // <= 而不是 ===：时钟回拨（NTP 校准、手动改时间）时也要保证不回退 ——
  // 版本号一旦倒退，乐观锁会把"旧版本"当成"新版本"放行。
  if (ms <= lastMs) {
    lastMs = lastMs + 1
  } else {
    lastMs = ms
  }
  return new Date(lastMs).toISOString()
}
